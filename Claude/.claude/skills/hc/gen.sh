#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
{
  cat <<'HEAD'
---
name: hc
description: "Use hc (herdr-core), the CLI behind the Herdr app, to run programs and coding agents in persistent terminals: delegate tasks to background agents, send/read/wait on terminals, run commands or edit files on other machines, and change the Herdr app window (spaces, tabs, panes) via herdr-app. Use when the user mentions hc, herdr-core, or the Herdr app, or when HC_TERMINAL_ID is set and they ask to delegate or run something in a terminal. Not the older `herdr` TUI."
---

HEAD
  echo "<!-- Generated by gen.sh from $(hc --version). Rerun after hc update. -->"
  echo
  echo 'Your terminal address: `$HC_TERMINAL_ID`.'
  echo
  hc --skill
  echo
  herdr-app --skill
} > SKILL.md
